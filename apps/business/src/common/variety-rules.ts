/** 生成该品种的 Skill 文档（deepagents 需要 YAML frontmatter）。 */
export function skillDoc(variety: string): string {
  return `---
name: ${variety}套期保值分析
description: 依据 workspace 的敞口台账、行情与企业套保政策，按 ${variety} 的合约与品质规则给出保值方向、目标手数、参考点位区间与前提条件，并输出严格符合 hedge_advice schema 的 JSON。合约乘数、交割月、品质分级与升贴水一律以 /data/品种资料/ 为准，不得凭记忆作答。
---

# ${variety}套期保值分析 Skill

## 权威规则来源（不得凭记忆）
- 品种合约与品质规则：/data/品种资料/（合约规则.md、品质与升贴水.md）
- 企业稳定事实：/data/长期记忆.md
- 企业当前状态：/data/日常状态.md

## 分析口径
1. 按风险池汇总净敞口（产季|地区|等级|期限），不跨池净额。
2. 正敞口（持库存怕跌）→ 卖出保值 / 买保护性看跌；负敞口（需采购怕涨）→ 买入保值 / 买保护性看涨。
3. 目标手数 = ⌊ 净吨 × 授权套保比例 ÷ 合约乘数 ⌋，向下取整，不突破实需与授权上限。
4. 合约乘数、交割月、品质分级与升贴水，一律查 /data/品种资料/。

## 输出
- 严格按 hedge_advice schema：给出敞口、建议（含参考点位区间）、阻断项与合规声明。
- lineage.rule_refs 需引用 /data/品种资料/ 中的具体文件。
`;
}
